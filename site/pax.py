# -*- coding: utf-8 -*-
"""`links[].pax_url` 을 **쓰기 전에** 검사한다 — 빌드가 막는 것 넷째.

계약(백엔드 `3b41d52`, `DECISIONS.md` 2026-09-22 (4))은 예약처마다 **인원 `{n}` 을 끼울 URL 한 벌**을 준다.
프론트가 하는 일은 하나뿐이다 — **`{n}` 하나만 치환한다.** 그 밖의 URL 조작은 금지다.

🔴 **왜 빌드에서 막나.** 이 값이 틀려도 **화면은 멀쩡하다.** 칩은 그려지고 링크는 눌리고 예약처도 열린다 —
인원만 조용히 1명으로 간다. 사용자는 `4명` 을 고르고 4명 값을 본다고 믿은 채 예약처에서 1인 가격을 본다.
**우리가 화면에서 한 약속이 거짓이 되는데 아무 예외도 안 난다.** 그래서 산출물을 쓰기 전에 여기서 멈춘다.

백엔드가 생산 쪽에서 같은 것을 검사한다(`{n}`→`1` 이 `url` 과 바이트 동일 · `{n}` 은 인코딩 바깥).
**그래도 소비 쪽에서 한 번 더 잰다** — 기획이 권했고, 같은 사실을 두 곳이 각자 확인하면 한쪽이 갈릴 때 드러난다.
(이 저장소가 다섯 번 겪은 「같은 사실이 두 곳에 있으면 갈라진다」의 **반대쪽 쓰임**이다:
사본을 두는 게 아니라 **검사를 두는 것**이라 갈리면 빌드가 시끄러워진다.)

무엇을 막나:

| 경우 | 판정 | 왜 |
|---|---|---|
| `pax_url` 키가 없다 | 🔴 **실패** | 계약상 `required`. 없으면 인원 칩이 조용히 아무 일도 안 하게 된다 |
| `pax_url` 이 `null` | ✅ 통과 | 그 예약처는 인원을 못 받는다는 **뜻이 있는 값**이다(화면에 `1인 기준으로 열려요`) |
| `{n}` 이 0개거나 2개 이상 | 🔴 **실패** | 치환이 한 자리가 아니면 무엇을 바꿨는지 말할 수 없다 |
| `{n}`→`1` ≠ `url` | 🔴 **실패** | **1명은 지금과 똑같아야 한다.** 다르면 인원을 안 골랐는데 링크가 바뀐 것이다 |
"""

TOKEN = "{n}"


def problems(deals):
    """막아야 할 것들을 사람이 읽을 문장으로 돌려준다. 빈 리스트면 통과.

    딜 전체를 훑는다 — **여집합으로 센다.** 「틀린 것만 본다」가 아니라 **모든 링크가 셋 중
    하나로 판정됐는지**를 같이 확인한다(`PLAN.md` 함정 11). 아래 `summary()` 가 그 수를 낸다.
    """
    bad = []
    for d in deals:
        for ln in d.get("links") or []:
            where = "%s · %s" % (d.get("ko", "?"), ln.get("name", "?"))
            if "pax_url" not in ln:
                bad.append("%s — `pax_url` 키가 없다(계약상 required)" % where)
                continue
            px = ln["pax_url"]
            if px is None:
                continue
            n = px.count(TOKEN)
            if n != 1:
                bad.append("%s — `{n}` 이 %d 개다(정확히 하나여야 한다)" % (where, n))
                continue
            if px.replace(TOKEN, "1") != ln.get("url"):
                bad.append("%s — `{n}`→`1` 이 `url` 과 다르다\n"
                           "        url      = %s\n"
                           "        pax_url  = %s" % (where, ln.get("url"), px))
    return bad


def summary(deals):
    """`(치환 가능, 인원 못 받음, 링크 전체)` — 「몇 개를 실제로 쟀나」를 로그에 적기 위한 것.

    **절대값을 기대하지 않는다**(딜 수는 매일 바뀐다). 대신 셋의 합이 링크 전체와 맞는지를 본다 —
    어느 갈래에도 안 든 링크가 있으면 검사가 그 링크를 안 본 것이다.
    """
    ok = none = total = 0
    for d in deals:
        for ln in d.get("links") or []:
            total += 1
            if ln.get("pax_url") is None:
                none += 1
            else:
                ok += 1
    return ok, none, total
